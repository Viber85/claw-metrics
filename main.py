"""Claw Metrics v0.1 — safe, isolated MangoHud configuration writer.
No TDP writes; Panel de Control retains control of the device.
"""
import json
import os
import pathlib
import tempfile
import shlex

DEFAULTS = {
    "enabled": True, "fontsize": 18, "opacity": 65,
    "fps": True, "frametime": True, "cpu": True, "gpu": True,
    "ram": True, "vram": True, "battery": True,
    "power": True, "time": True, "tdp": False,
}
KEYS = tuple(DEFAULTS)
# The service is normally executed as root: use the invoking desktop user instead.
def user_home():
    explicit = os.getenv("DECKY_USER_HOME")
    if explicit and pathlib.Path(explicit).is_absolute():
        return pathlib.Path(explicit)
    for name in ("DECKY_USER", "SUDO_USER"):
        value = os.getenv(name, "")
        if value and value != "root":
            import pwd
            try:
                return pathlib.Path(pwd.getpwnam(value).pw_dir)
            except KeyError:
                pass
    for path in ("/home/gamer", "/home/deck", "/home/user"):
        if pathlib.Path(path).is_dir():
            return pathlib.Path(path)
    return pathlib.Path.home()

BASE = user_home() / ".config" / "ClawMetrics"
CONFIG = BASE / "settings.json"
HUD = BASE / "MangoHud.conf"

def normalize(payload):
    d = dict(DEFAULTS)
    if isinstance(payload, dict):
        for key in KEYS:
            v = payload.get(key)
            if isinstance(DEFAULTS[key], bool) and type(v) is bool:
                d[key] = v
            elif key == "fontsize" and type(v) is int:
                d[key] = min(28, max(12, v))
            elif key == "opacity" and type(v) is int:
                d[key] = min(100, max(0, v))
    return d

def write_atomic(path, content):
    BASE.mkdir(parents=True, exist_ok=True)
    BASE.chmod(0o755)
    fd, temporary = tempfile.mkstemp(dir=str(BASE), prefix=".tmp-")
    try:
        with os.fdopen(fd, "w", encoding="utf-8") as file:
            file.write(content)
            # mkstemp defaults to 0600; the game runs as the desktop user.
            os.fchmod(file.fileno(), 0o644)
        os.replace(temporary, path)
    finally:
        if os.path.exists(temporary):
            os.unlink(temporary)

def mango_config(d):
    lines = [
        "# Generated by Claw Metrics v0.1. Do not edit: the QAM plugin regenerates this file.",
        "legacy_layout=0", "horizontal", "horizontal_stretch=1",
        # MangoHud battery_time in compact mode forces TableSetColumnIndex(0),
        # overwriting FPS and clock. Horizontal mode already provides one row.
        "hud_compact=0", "hud_no_margin", "position=top-left",
        "round_corners=5", "background_color=111821", "text_color=F5F7FB",
        "fps_color=8CE4AC", "frametime_color=8CE4AC",
        "background_alpha=" + str(d["opacity"] / 100),
        "font_size=" + str(d["fontsize"]),
        "fps=" + ("1" if d["enabled"] and d["fps"] else "0"),
        "frametime=" + ("1" if d["enabled"] and d["frametime"] else "0"),
        "frame_timing=" + ("1" if d["enabled"] and d["frametime"] else "0"),
        "cpu_stats=" + ("1" if d["enabled"] and d["cpu"] else "0"),
        "gpu_stats=" + ("1" if d["enabled"] and d["gpu"] else "0"),
        "cpu_temp=" + ("1" if d["enabled"] and d["cpu"] else "0"),
        "cpu_mhz=" + ("1" if d["enabled"] and d["cpu"] else "0"),
        "gpu_temp=" + ("1" if d["enabled"] and d["gpu"] else "0"),
        "gpu_core_clock=" + ("1" if d["enabled"] and d["gpu"] else "0"),
        "ram=" + ("1" if d["enabled"] and d["ram"] else "0"),
        "vram=" + ("1" if d["enabled"] and d["vram"] else "0"),
        "battery=" + ("1" if d["enabled"] and d["battery"] else "0"),
        "battery_icon=" + ("1" if d["enabled"] and d["battery"] else "0"),
        "battery_time=" + ("1" if d["enabled"] and d["battery"] else "0"),
        "cpu_power=" + ("1" if d["enabled"] and d["power"] else "0"),
        "gpu_power=" + ("1" if d["enabled"] and d["power"] else "0"),
        "time=" + ("1" if d["enabled"] and d["time"] else "0"),
        'time_format="%H:%M"',
        "no_display=" + ("0" if d["enabled"] else "1"),
        # Start with ImGui's full column capacity. MangoHud measures the
        # active subcolumns and reduces this automatically after rendering.
        # 20 can wrap battery/time into the FPS cells on the first frame.
        "table_columns=64",
    ]
    # TDP setting intentionally omitted: MangoHud power limits are not
    # authoritative for the value Panel de Control has actually applied.
    return "\n".join(lines) + "\n"

class Plugin:
    async def _main(self):
        if not CONFIG.is_file():
            write_atomic(CONFIG, json.dumps(DEFAULTS, indent=2) + "\n")
        try:
            with CONFIG.open(encoding="utf-8") as f:
                settings = normalize(json.load(f))
        except (OSError, ValueError):
            settings = dict(DEFAULTS)
        write_atomic(HUD, mango_config(settings))

    async def get_settings(self):
        try:
            with CONFIG.open(encoding="utf-8") as f:
                return normalize(json.load(f))
        except (OSError, ValueError):
            return dict(DEFAULTS)

    async def save_settings(self, settings: dict):
        data = normalize(settings)
        write_atomic(CONFIG, json.dumps(data, indent=2) + "\n")
        write_atomic(HUD, mango_config(data))
        return {"ok": True, "settings": data, "config_path": str(HUD)}

    async def get_info(self):
        return {
            "config_path": str(HUD),
            "launch_option": "MANGOHUD_CONFIGFILE=" + shlex.quote(str(HUD)) + " mangohud %command%",
            "config_readable": HUD.is_file() and bool(HUD.stat().st_mode & 0o004),
            "tdp_note": "TDP setpoint integration with Panel de Control is not implemented in v0.1.",
            "power_note": "CPU/GPU sensor power is not the same as total system battery draw."
        }
